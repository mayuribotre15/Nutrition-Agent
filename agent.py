"""
Nutrition Agentic AI — Core Agent Logic
Handles multi-step user data collection, guardrails, plan generation, and Q&A.
"""

import re
from granite_llm import GraniteLLM
from config import Config

MEDICAL_DISCLAIMER = """
---
⚕️ **Medical Disclaimer**

The nutrition information and meal plans provided by this AI assistant are for **general informational and educational purposes only**. They are **not** a substitute for professional medical advice, diagnosis, or treatment.

- Always consult a **qualified healthcare provider** or **registered dietitian** before making significant changes to your diet, especially if you have existing medical conditions such as diabetes, hypertension, kidney disease, or are pregnant/breastfeeding.
- Individual nutritional needs vary; what works for one person may not be appropriate for another.
- This AI does not have access to your full medical records and cannot replace a clinical evaluation.
- **In case of a medical emergency, contact emergency services immediately.**

*Generated by Nutrition AI powered by IBM Granite — IBM WatsonX*
---
"""

SYSTEM_PROMPT = """You are NutriGuide, a compassionate, knowledgeable, and ethical Nutrition AI assistant powered by IBM Granite.

Your purpose is to help users create personalized, safe, and balanced nutrition plans based on their profile.

## Core Principles (AI Ethics & HAM Guidelines):
- Be **Helpful**: Provide clear, actionable, evidence-based nutrition advice.
- Be **Accurate**: Base all recommendations on established nutritional science (WHO, ICMR, NIH guidelines).
- Be **Mindful (HAM)**: Always use a warm, respectful, inclusive, and non-judgmental tone.
- **Never** provide medical diagnoses or prescribe medications.
- **Never** recommend extreme dieting, dangerous fasting, or weight-loss supplements.
- **Always** encourage consulting a registered dietitian or doctor for medical conditions.
- Respect cultural, religious, and personal dietary preferences without bias.
- Be transparent about the limits of AI-generated advice.

## Guardrails:
- If asked about harmful, dangerous, or unethical dietary practices, firmly but kindly decline and redirect.
- If the user shows signs of an eating disorder or mental health crisis, provide supportive resources.
- Never guarantee specific medical outcomes (e.g., "this will cure your diabetes").
- Always include a reminder to consult a healthcare professional for medical conditions.

## Nutrition Plan Format:
When generating a plan, structure it as:
1. User Profile Summary
2. Nutritional Goals & Caloric Target
3. Macronutrient Breakdown (Carbs, Protein, Fat, Fiber)
4. 7-Day Meal Plan (Breakfast, Mid-Morning Snack, Lunch, Evening Snack, Dinner)
5. Hydration Guidelines
6. Foods to Emphasize & Foods to Limit (based on medical history)
7. Lifestyle Tips
8. When to seek professional help
"""

# Conversation stages
STAGE_GREETING = "greeting"
STAGE_NAME = "collect_name"
STAGE_AGE = "collect_age"
STAGE_DIET = "collect_diet"
STAGE_MEDICAL = "collect_medical"
STAGE_LOCATION = "collect_location"
STAGE_GENERATING = "generating"
STAGE_QA = "qa"


class NutritionAgent:
    """
    Agentic AI system that orchestrates multi-turn conversations to collect
    user details and generate a personalized nutrition plan via IBM Granite.
    """

    def __init__(self):
        self.llm = GraniteLLM()
        self.stage = STAGE_GREETING
        self.user_data = {}
        self.conversation_history = []
        self.plan_generated = False

    # ─────────────────────────────── Guardrails ──────────────────────────────

    def _check_guardrails(self, message: str) -> str | None:
        """
        Check for harmful content. Returns a safety response if triggered, else None.
        """
        msg_lower = message.lower()
        for keyword in Config.HARMFUL_KEYWORDS:
            if keyword in msg_lower:
                return (
                    "I'm sorry, but I'm unable to provide advice on that topic as it may be harmful to your health. "
                    "If you're struggling with disordered eating or any health crisis, please reach out to a "
                    "qualified healthcare professional or call a helpline in your country. "
                    "I'm here to support healthy, balanced, and safe nutrition. How can I help you with that? 🌿"
                )

        # Detect eating disorder signs
        eating_disorder_signals = ["not eating", "i don't eat", "i refuse to eat", "i hate food", "afraid to eat"]
        if any(sig in msg_lower for sig in eating_disorder_signals):
            return (
                "I hear you, and I want you to know that your feelings are valid. "
                "If you're experiencing a difficult relationship with food, please consider speaking with a "
                "registered dietitian or a mental health professional — they can provide the compassionate, "
                "personalized support you deserve. 💚 I'm here to help you build a positive relationship with food."
            )

        return None

    # ──────────────────────────── Stage Handlers ─────────────────────────────

    def _handle_greeting(self) -> dict:
        self.stage = STAGE_NAME
        return {
            "message": (
                "👋 Welcome to **NutriGuide** — Your Personal Nutrition AI!\n\n"
                "I'm powered by **IBM Granite** and here to help you build a healthy, personalized meal plan "
                "tailored to your needs, preferences, and health goals.\n\n"
                "Let's start by getting to know you a little. 🌿\n\n"
                "**What is your full name?**"
            ),
            "stage": self.stage,
            "progress": 0,
        }

    def _handle_name(self, message: str) -> dict:
        name = message.strip().title()
        if len(name) < 2 or any(char.isdigit() for char in name):
            return {
                "message": "Please enter a valid name (letters only, at least 2 characters).",
                "stage": self.stage,
                "progress": 5,
            }
        self.user_data["name"] = name
        self.stage = STAGE_AGE
        return {
            "message": (
                f"Nice to meet you, **{name}**! 😊\n\n"
                "**How old are you?** (Please enter your age in years, e.g., 28)"
            ),
            "stage": self.stage,
            "progress": 15,
        }

    def _handle_age(self, message: str) -> dict:
        try:
            age = int(re.search(r"\d+", message).group())
            if age < 5 or age > 110:
                raise ValueError("Age out of range")
            self.user_data["age"] = age
            self.stage = STAGE_DIET
            return {
                "message": (
                    f"Got it — **{age} years old**. ✅\n\n"
                    "**What is your dietary preference?**\n\n"
                    "Please choose one:\n"
                    "- 🥦 **Vegetarian** (no meat/seafood)\n"
                    "- 🥩 **Non-Vegetarian** (includes meat, poultry, seafood)\n"
                    "- 🌱 **Vegan** (no animal products)\n"
                    "- 🐟 **Pescatarian** (vegetarian + seafood)\n"
                    "- 🍽️ **Flexitarian** (mostly plant-based, occasionally meat)"
                ),
                "stage": self.stage,
                "progress": 30,
            }
        except (AttributeError, ValueError):
            return {
                "message": "Please enter a valid age (between 5 and 110 years).",
                "stage": self.stage,
                "progress": 15,
            }

    def _handle_diet(self, message: str) -> dict:
        msg_lower = message.lower()
        diet_map = {
            "vegan": "Vegan",
            "pescatarian": "Pescatarian",
            "flexitarian": "Flexitarian",
            "vegetarian": "Vegetarian",
            "veg": "Vegetarian",
            "non-veg": "Non-Vegetarian",
            "non veg": "Non-Vegetarian",
            "nonveg": "Non-Vegetarian",
            "meat": "Non-Vegetarian",
        }
        detected = None
        for key, val in diet_map.items():
            if key in msg_lower:
                detected = val
                break

        if not detected:
            return {
                "message": (
                    "I didn't quite catch that. Please type one of:\n"
                    "**Vegetarian**, **Non-Vegetarian**, **Vegan**, **Pescatarian**, or **Flexitarian**"
                ),
                "stage": self.stage,
                "progress": 30,
            }

        self.user_data["diet"] = detected
        self.stage = STAGE_MEDICAL
        return {
            "message": (
                f"Great choice — **{detected}** diet noted! 🥗\n\n"
                "**Do you have any medical conditions or health concerns I should consider?**\n\n"
                "For example: diabetes, high blood pressure, high cholesterol, thyroid disorder, "
                "kidney disease, PCOS, lactose intolerance, gluten intolerance, heart disease, etc.\n\n"
                "*(Type 'none' if you have no known medical conditions)*"
            ),
            "stage": self.stage,
            "progress": 50,
        }

    def _handle_medical(self, message: str) -> dict:
        medical = message.strip()
        if medical.lower() in ["none", "no", "nothing", "n/a", "nil"]:
            self.user_data["medical"] = "None"
        else:
            self.user_data["medical"] = medical
        self.stage = STAGE_LOCATION
        return {
            "message": (
                "Thank you for sharing that — I'll make sure the plan respects your health needs. 🏥\n\n"
                "**Finally, where are you located?**\n\n"
                "Please share your **city and country** (e.g., 'Mumbai, India' or 'New York, USA').\n"
                "This helps me recommend locally available foods."
            ),
            "stage": self.stage,
            "progress": 70,
        }

    def _handle_location(self, message: str) -> dict:
        location = message.strip().title()
        if len(location) < 3:
            return {
                "message": "Please enter your city and country (e.g., 'Chennai, India').",
                "stage": self.stage,
                "progress": 70,
            }
        self.user_data["location"] = location
        self.stage = STAGE_GENERATING
        return {
            "message": (
                f"Perfect! I have everything I need. 🎉\n\n"
                f"**Here's your profile summary:**\n"
                f"- 👤 **Name:** {self.user_data['name']}\n"
                f"- 🎂 **Age:** {self.user_data['age']} years\n"
                f"- 🥗 **Diet:** {self.user_data['diet']}\n"
                f"- 🏥 **Medical History:** {self.user_data['medical']}\n"
                f"- 📍 **Location:** {self.user_data['location']}\n\n"
                "⏳ **Generating your personalized nutrition plan... Please wait a moment.**"
            ),
            "stage": self.stage,
            "progress": 85,
            "generating": True,
        }

    def _generate_nutrition_plan(self) -> dict:
        """Build a prompt and call IBM Granite to generate the full nutrition plan."""
        ud = self.user_data
        plan_prompt = f"""
Please generate a detailed, personalized 7-day nutrition plan for the following individual:

**User Profile:**
- Name: {ud['name']}
- Age: {ud['age']} years
- Dietary Preference: {ud['diet']}
- Medical Conditions: {ud['medical']}
- Location: {ud['location']}

**Requirements:**
1. Calculate appropriate daily caloric intake based on age and health conditions.
2. Design meals using locally available foods in {ud['location']}.
3. Account for all medical conditions listed — e.g., for diabetes: low-GI foods, limit refined carbs; for blood pressure: low sodium, high potassium.
4. Respect the {ud['diet']} dietary preference strictly.
5. Include a variety of nutrients across the 7 days.
6. Keep meal portions realistic and sustainable.
7. Add hydration and lifestyle tips.
8. Include foods to emphasize and foods to limit.
9. Format clearly with headings and bullet points.
10. End with a reminder to consult a healthcare professional.

Generate a warm, encouraging, and detailed nutrition plan now.
"""
        try:
            plan = self.llm.generate(plan_prompt, system_prompt=SYSTEM_PROMPT)
        except Exception as e:
            plan = (
                f"I encountered an issue connecting to the AI model: {str(e)}\n\n"
                "Please check your network connection and API credentials, then try again."
            )

        full_response = plan + "\n\n" + MEDICAL_DISCLAIMER
        self.plan_generated = True
        self.stage = STAGE_QA

        # Seed conversation history for follow-up Q&A
        self.conversation_history = [
            {"role": "user", "content": f"Generate nutrition plan for: {ud}"},
            {"role": "assistant", "content": plan},
        ]

        return {
            "message": full_response,
            "stage": self.stage,
            "progress": 100,
            "plan_complete": True,
        }

    def _handle_qa(self, message: str) -> dict:
        """Handle follow-up queries using conversation history for context."""
        self.conversation_history.append({"role": "user", "content": message})

        qa_prompt = (
            f"The user ({self.user_data.get('name', 'User')}) has a follow-up question about their nutrition plan. "
            f"Answer helpfully, safely, and accurately based on their profile: {self.user_data}\n\n"
            f"Question: {message}"
        )

        try:
            answer = self.llm.generate_with_history(
                self.conversation_history[-6:],  # Keep last 6 turns for context
                system_prompt=SYSTEM_PROMPT,
            )
        except Exception as e:
            answer = f"I'm having trouble reaching the AI model right now: {str(e)}. Please try again in a moment."

        self.conversation_history.append({"role": "assistant", "content": answer})

        return {
            "message": answer + "\n\n*— NutriGuide AI | Always consult a healthcare professional for medical advice.*",
            "stage": self.stage,
            "progress": 100,
        }

    # ─────────────────────────── Main Entry Point ────────────────────────────

    def process_message(self, message: str) -> dict:
        """
        Main message router. Checks guardrails first, then delegates to stage handlers.
        """
        # 1. Guardrail check
        safety_response = self._check_guardrails(message)
        if safety_response:
            return {"message": safety_response, "stage": self.stage, "progress": getattr(self, "_progress", 0)}

        # 2. Initial greeting (triggered once)
        if self.stage == STAGE_GREETING:
            return self._handle_greeting()

        # 3. Data collection stages
        if self.stage == STAGE_NAME:
            return self._handle_name(message)
        if self.stage == STAGE_AGE:
            return self._handle_age(message)
        if self.stage == STAGE_DIET:
            return self._handle_diet(message)
        if self.stage == STAGE_MEDICAL:
            return self._handle_medical(message)
        if self.stage == STAGE_LOCATION:
            return self._handle_location(message)

        # 4. Plan generation
        if self.stage == STAGE_GENERATING:
            return self._generate_nutrition_plan()

        # 5. Q&A mode
        if self.stage == STAGE_QA:
            return self._handle_qa(message)

        return {"message": "Something went wrong. Please refresh and try again.", "stage": self.stage, "progress": 0}
